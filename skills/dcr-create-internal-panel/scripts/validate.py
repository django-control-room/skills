#!/usr/bin/env python3
"""Static checks for an internal DCR panel app produced by dcr-create-internal-panel.

The app is generated by ``manage.py dcr_startpanel``.

Usage:
    python scripts/validate.py /path/to/django-project/dcr_webhook_failures

Does not import Django. Exits 1 if any error is found.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SKILLS_IMPORT = re.compile(
    r"(?:from|import)\s+(?:skills|dcr_create_package_panel|dcr_create_internal_panel|dcr-create-package-panel|dcr-create-internal-panel)\b"
)
PERMISSION = re.compile(r"permission_required\s*\(")
GET_CONTEXT = re.compile(r"panel_config\.get_context\s*\(")
AGENT_SCOPE = re.compile(r'scope\s*=\s*"agent_')
VIEW_DEF = re.compile(r"^def\s+\w+\s*\(\s*request", re.M)
PACKAGE_SHELL = (
    "pyproject.toml",
    "setup.py",
    "MANIFEST.in",
    "mkdocs.yml",
    "docker-compose.yml",
    "Dockerfile",
)

# If the user pointed validate at a baked *package* by mistake.
PACKAGE_ONLY_HINTS = ("example_project",)


class Issue:
    def __init__(self, level: str, code: str, message: str, path: str = ""):
        self.level = level
        self.code = code
        self.message = message
        self.path = path

    def as_dict(self) -> dict:
        return {
            "level": self.level,
            "code": self.code,
            "message": self.message,
            "path": self.path,
        }


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def _is_app_dir(path: Path) -> bool:
    return (path / "panel.py").is_file() and (path / "conf.py").is_file()


def validate(app_dir: Path) -> list[Issue]:
    issues: list[Issue] = []
    app_dir = app_dir.resolve()

    if not app_dir.is_dir():
        issues.append(Issue("error", "not_a_dir", "Not a directory.", str(app_dir)))
        return issues

    if not _is_app_dir(app_dir):
        issues.append(Issue(
            "error",
            "not_a_panel_app",
            "Expected a Django app directory containing panel.py and conf.py "
            "(the app created by dcr_startpanel, not a package root).",
            str(app_dir),
        ))
        return issues

    for name in PACKAGE_SHELL:
        if (app_dir / name).exists():
            issues.append(Issue(
                "error",
                "package_shell",
                f"Found {name} — this skill creates a Django app, not a panel package. "
                "Use dcr-create-package-panel for publishable packages.",
                name,
            ))
    for name in PACKAGE_ONLY_HINTS:
        if (app_dir / name).exists():
            issues.append(Issue(
                "error",
                "package_shell",
                f"Found {name}/ — do not copy a package shell into the host project.",
                name,
            ))

    for rel in ("panel.py", "conf.py", "views.py", "urls.py", "apps.py"):
        if not (app_dir / rel).is_file():
            issues.append(Issue("error", "missing_file", f"Missing {rel}.", rel))

    for path in app_dir.rglob("*.py"):
        text = _read(path)
        if SKILLS_IMPORT.search(text):
            issues.append(Issue(
                "error",
                "skills_import",
                "Do not import from the skills repository. Depend on dj-control-room-base.",
                str(path.relative_to(app_dir)),
            ))

    panel = _read(app_dir / "panel.py")
    if panel:
        if re.search(r'description\s*=\s*"[^"]*Control Room panel"', panel):
            issues.append(Issue(
                "warning",
                "stub_panel_description",
                "Replace the generated panel description with a real one.",
                "panel.py",
            ))
        if re.search(r'docs_url\s*=\s*"https?://', panel) or re.search(
            r'pypi_url\s*=\s*"https?://', panel
        ):
            issues.append(Issue(
                "error",
                "package_urls",
                "Internal panels must not set docs_url / pypi_url (those imply a published package).",
                "panel.py",
            ))

    apps = _read(app_dir / "apps.py")
    if apps and "registry.register" not in apps:
        issues.append(Issue(
            "warning",
            "no_ready_register",
            "apps.py should call registry.register(..., panel_id=...) from ready().",
            "apps.py",
        ))

    views = _read(app_dir / "views.py")
    if views:
        if VIEW_DEF.search(views) and not PERMISSION.search(views):
            issues.append(Issue(
                "error",
                "no_permission_required",
                "Views must use @panel_config.permission_required(scope).",
                "views.py",
            ))
        if "render(" in views and not GET_CONTEXT.search(views):
            issues.append(Issue(
                "error",
                "no_get_context",
                "Build template context with panel_config.get_context(request, ...).",
                "views.py",
            ))
        if 'permission_required("index")' in views or "permission_required('index')" in views:
            issues.append(Issue(
                "warning",
                "stub_index_scope",
                'Replace the generated "index" scope with a descriptive name '
                "(e.g. package_list). See dcr-reference/scopes.md.",
                "views.py",
            ))

    tools = _read(app_dir / "tools.py")
    if tools:
        if "hello_world" in tools or "handle_hello_world" in tools:
            issues.append(Issue(
                "warning",
                "hello_world_stub",
                "Replace or delete the hello_world stub (not from dcr_startpanel).",
                "tools.py",
            ))
        if "@registry.register" in tools and not AGENT_SCOPE.search(tools):
            issues.append(Issue(
                "error",
                "missing_agent_scope",
                'MCP tools must use scope="agent_...".',
                "tools.py",
            ))

    conf = _read(app_dir / "conf.py")
    if tools and conf and "tool_registry" not in conf and "tools=" not in conf:
        issues.append(Issue(
            "warning",
            "tools_not_wired",
            "conf.py should pass tools=tool_registry.tools to PanelConfig.",
            "conf.py",
        ))

    templates = app_dir / "templates" / "admin" / app_dir.name
    if templates.is_dir():
        for html in templates.rglob("*.html"):
            text = _read(html)
            rel = str(html.relative_to(app_dir))
            if re.search(r'class="[^"]*\bbutton\b', text):
                issues.append(Issue(
                    "warning",
                    "admin_button_class",
                    "Use dcr-btn, not Django admin .button. See dcr-reference/design-system.md.",
                    rel,
                ))
            if html.name == "index.html":
                if (
                    "panel-welcome" in text
                    or "welcome_graphic" in text
                    or "Your panel is set up and ready to build" in text
                ):
                    issues.append(Issue(
                        "warning",
                        "welcome_stub",
                        "index.html still looks like the dcr_startpanel starter page.",
                        rel,
                    ))
                if "dcr-page-header" not in text:
                    issues.append(Issue(
                        "warning",
                        "missing_dcr_header",
                        "List page should use dcr-page-header. See dcr-reference/design-system.md.",
                        rel,
                    ))

    styles = app_dir / "static" / app_dir.name / "css" / "styles.css"
    if styles.is_file():
        css = _read(styles)
        if "DJ CONTROL ROOM - Design System" in css or "--dcr-color-text:" in css:
            issues.append(Issue(
                "error",
                "copied_design_system",
                "Do not copy design-system.css into the panel. Extend panel_base.html.",
                str(styles.relative_to(app_dir)),
            ))
        elif re.search(r"#[0-9a-fA-F]{3,8}\b", css) and "panel-welcome" not in css:
            issues.append(Issue(
                "warning",
                "hardcoded_color",
                "Panel CSS should use var(--dcr-*) tokens, not hex colours.",
                str(styles.relative_to(app_dir)),
            ))

    scopes_doc = _read(app_dir / "scopes.md")
    if not scopes_doc:
        issues.append(Issue(
            "warning",
            "missing_scopes_doc",
            "Expected scopes.md in the app (no MkDocs docs/ tree for internal panels).",
            "scopes.md",
        ))
    elif "agent_hello_world" in scopes_doc or (
        "`index`" in scopes_doc and "hello_world" in scopes_doc
    ):
        issues.append(Issue(
            "warning",
            "stub_scopes_doc",
            "scopes.md still documents stub scopes.",
            "scopes.md",
        ))

    return issues


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Validate an internal (unpackaged) DCR panel Django app."
    )
    parser.add_argument("app_dir", type=Path)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    if not args.app_dir.is_dir():
        print(f"Not a directory: {args.app_dir}", file=sys.stderr)
        return 2

    issues = validate(args.app_dir)
    errors = [i for i in issues if i.level == "error"]
    warnings = [i for i in issues if i.level == "warning"]

    if args.json:
        print(json.dumps([i.as_dict() for i in issues], indent=2))
    else:
        if not issues:
            print(f"OK  {args.app_dir}")
        for issue in issues:
            loc = f"  ({issue.path})" if issue.path else ""
            print(f"{issue.level.upper():7} {issue.code}: {issue.message}{loc}")
        print(f"{len(errors)} error(s), {len(warnings)} warning(s)")

    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
